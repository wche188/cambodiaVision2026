// Get all provinces
export const getProvinces = () => {
  return Object.keys(cambodiaLocations).sort();
};

// Get districts for a specific province
export const getDistricts = (province) => {
  if (!province || !cambodiaLocations[province]) {
    return [];
  }
  return cambodiaLocations[province].districts;
};